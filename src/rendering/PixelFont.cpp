void PixelFont::drawText(SDL_Renderer* renderer, const std::string& text, int x, int y, int scale,
                         SDL_Color color) {
    if (renderer == nullptr || scale <= 0) {
        return;
    }
    const auto& table = glyphs();
    static const Glyph kMissing = {"##.", "..#", ".#.", "..#", "##."};  // '?'-ish fallback
    std::vector<SDL_Rect> rects;
    rects.reserve(text.size() * 8);
    int cx = x;
    for (char raw : text) {
        const char c = normalize(raw);
        const auto it = table.find(c);
        const Glyph& g = it != table.end() ? it->second : kMissing;
        for (int row = 0; row < kGlyphH; ++row) {
            for (int col = 0; col < kGlyphW; ++col) {
                if (g[row][col] == '#') {
                    rects.push_back({cx + col * scale, y + row * scale, scale, scale});
                }
            }
        }
        cx += (kGlyphW + 1) * scale;
    }
    if (rects.empty()) {
        return;
    }
    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
    SDL_RenderFillRects(renderer, rects.data(), static_cast<int>(rects.size()));
}

int PixelFont::textWidth(const std::string& text, int scale) {
    if (text.empty()) {
        return 0;
    }
    return static_cast<int>(text.size()) * (kGlyphW + 1) * scale - scale;
}
